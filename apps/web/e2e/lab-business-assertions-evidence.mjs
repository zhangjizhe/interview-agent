import assert from 'node:assert/strict';
import { questionInputSnapshot } from './lab-question-input-snapshot.mjs';

export async function verifyBusinessAssertions(page, context, origin) {
  assert.equal(process.env.LAB_FIXTURE_SYNTHETIC, '1');
  assert.equal(origin, 'http://localhost:5176');
  const token = await page.evaluate(() => localStorage.getItem('ia_access_token'));
  const headers = { Authorization: `Bearer ${token}` };
  const before = await questionInputSnapshot();
  const agentsResponse = await context.request.get(`${origin}/api/agent-lab/agents`, { headers });
  assert.equal(agentsResponse.status(), 200);
  const agent = (await agentsResponse.json()).find(item => item.key === 'synthetic-release-invalid-score');
  assert.ok(agent, 'actual failed business evaluation fixture');
  const select = page.getByRole('combobox', { name: 'Agent', exact: true });
  await select.locator(`option[value="${agent.id}"]`).waitFor({ state: 'attached' });
  await select.selectOption(agent.id);
  const evaluations = await context.request.get(`${origin}/api/agent-lab/agents/${agent.id}/evaluations`, { headers });
  assert.equal(evaluations.status(), 200);
  const evaluation = (await evaluations.json()).find(item => item.status === 'COMPLETED' && item.failedCases === 10);
  assert.ok(evaluation);
  await page.getByRole('button', { name: `查看 ${evaluation.id} 的逐项证据`, exact: true }).click();
  const evidence = page.getByRole('region', { name: '逐项断言证据', exact: true });
  await evidence.getByRole('heading', { name: `逐项断言证据 · ${evaluation.id}`, exact: true }).waitFor();
  await evidence.getByText('score-range · 未通过', { exact: true }).first().waitFor();
  await evidence.getByText(/语义质量未评估/).first().waitFor();
  const detailsResponse = await context.request.get(`${origin}/api/agent-lab/evaluations/${evaluation.id}`, { headers });
  assert.equal(detailsResponse.status(), 200);
  const details = await detailsResponse.json();
  const reference = details.results[0].evidence.samples[0].assertions.find(item => item.id === 'score-range').evidence.runId;
  await evidence.getByText(`Trace 引用：${reference}`, { exact: true }).first().waitFor();
  await page.getByRole('button', { name: '核验首次发布门禁', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '首次发布门禁：存在未通过的评测用例，不能发布。' }).waitFor();
  assert.equal(await page.getByRole('button', { name: '管理员发布', exact: true }).isDisabled(), true);

  await page.getByText('配置评测资产', { exact: true }).click();
  await page.getByLabel('Dataset key', { exact: true }).fill('browser-business-contract');
  await page.getByLabel('Dataset 名称', { exact: true }).fill('Browser business contract');
  const datasetReceipt = page.waitForResponse(response => response.url().endsWith('/api/agent-lab/datasets') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '创建 Dataset', exact: true }).click();
  const createdDatasetResponse = await datasetReceipt;
  assert.equal(createdDatasetResponse.status(), 201);
  const dataset = await createdDatasetResponse.json();
  const evaluatorReceipt = page.waitForResponse(response => response.url().endsWith('/api/agent-lab/evaluators') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '创建 Evaluator', exact: true }).click();
  const createdEvaluatorResponse = await evaluatorReceipt;
  assert.equal(createdEvaluatorResponse.status(), 201);
  const evaluator = await createdEvaluatorResponse.json();
  assert.equal(evaluator.type, 'BUSINESS_ASSERTIONS');
  assert.deepEqual(evaluator.config, { contractVersion: 'business-assertions/v1' });
  await page.getByLabel('Case key', { exact: true }).fill('browser-contract-case');
  await page.getByLabel('输入消息', { exact: true }).fill('Synthetic structured output contract only');
  await page.getByLabel('岗位族标签', { exact: true }).fill('synthetic-engineer');
  await page.getByLabel('技能标签', { exact: true }).fill('evaluation');
  await page.getByLabel('难度标签', { exact: true }).fill('foundation');
  await page.getByLabel('Case 责任人', { exact: true }).fill('fixture');
  await page.getByRole('checkbox', { name: '我确认该 Case 为自编合成样本，不含候选人或个人数据，允许用于发布评测。', exact: true }).check();
  const invalidContract = { contractVersion: 'business-assertions/v1', assertions: [{ id: 'unsafe', source: 'response-json', path: ['constructor'], op: 'exists' }] };
  await page.getByLabel('业务断言 JSON', { exact: true }).fill(JSON.stringify(invalidContract));
  const rejectedReceipt = page.waitForResponse(response => response.url().endsWith(`/datasets/${dataset.id}/cases`) && response.request().method() === 'POST');
  await page.getByRole('button', { name: '添加 Case 到当前 Dataset', exact: true }).click();
  assert.equal((await rejectedReceipt).status(), 400);
  await page.getByRole('status').filter({ hasText: '业务断言无效' }).waitFor();
  await page.getByRole('button', { name: '恢复业务断言范例', exact: true }).click();
  const savedReceipt = page.waitForResponse(response => response.url().endsWith(`/datasets/${dataset.id}/cases`) && response.request().method() === 'POST');
  await page.getByRole('button', { name: '添加 Case 到当前 Dataset', exact: true }).click();
  assert.equal((await savedReceipt).status(), 201);
  const persistedResponse = await context.request.get(`${origin}/api/agent-lab/datasets/${dataset.id}`, { headers });
  assert.equal(persistedResponse.status(), 200);
  const persisted = await persistedResponse.json();
  assert.equal(persisted.cases.length, 1);
  assert.equal(persisted.cases[0].expectedOutput.contractVersion, 'business-assertions/v1');
  assert.ok(persisted.cases[0].expectedOutput.assertions.length >= 2);
  assert.equal(persisted.cases[0].metadata.provenance.containsPersonalData, false);
  assert.deepEqual(await questionInputSnapshot(), before);
  console.log('PASS business assertion browser: persisted failing rule/reference, refused publication, actual evaluator/Case creation, unsafe path rejected and corrected; no provider/ledger increment, semantics unassessed');
}
